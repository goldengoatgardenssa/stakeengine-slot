export function getSymbolSVG(key) {
  for (const tier of Object.values(symbolSVGs)) {
    if (tier[key]) return tier[key];
  }
  return `<svg viewBox="0 0 100 100" xmlns="http://www.w3.org/2000/svg"><rect width="100" height="100" rx="12" fill="#334155"/><text x="50" y="60" text-anchor="middle" fill="#fff" font-size="24" font-family="system-ui">?</text></svg>`;
}

export function renderSymbolToDOM(key, size = 80) {
  const div = document.createElement("div");
  div.className = "storybook-symbol";
  div.style.width = `${size}px`;
  div.style.height = `${size}px`;
  div.innerHTML = getSymbolSVG(key);
  return div;
}

